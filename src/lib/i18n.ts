export type TranslationKey = typeof translations
export type Section = keyof TranslationKey

// Helper: get translated string
export function t(
  section: Section,
  key: string,
  lang: Lang,
): string {
  const sec = translations[section] as Record<string, Record<Lang, string>>
  return sec?.[key]?.[lang] ?? sec?.[key]?.['ru'] ?? key
}
